'use strict';
// ════════════════════════════════════════════════════════════════════════════
//  EA converter: strategy file → MetaTrader 5 Expert Advisor (.mq5)
//  (added 2026-10-30)
//
//  Writes the same rules the bot trades and the replay tests as a standalone
//  MQL5 Expert Advisor: MT5's own indicators (iMA, iRSI, iATR, ...), rules
//  checked once per new candle on finished candles only, the strategy's stop
//  and target sent with the order, its trailing stop, exit rule, time limit
//  and breakeven, sizing from a % risk of the balance, a spread check, and
//  the bot's entry hours around XM's daily break. Usage:
//      node tools/ea/export.js <strategy id>   → ea-export/<id>.mq5
//  Compile it in MetaEditor (F7) and test it in MT5's Strategy Tester before
//  running it anywhere.
// ════════════════════════════════════════════════════════════════════════════
const X = require('./expr');

const PRICE_FN = { open: 'P_open', high: 'P_high', low: 'P_low', close: 'P_close', volume: 'P_volume', median: 'P_median', typical: 'P_typical', weighted: 'P_weighted' };
const SCALAR_MQL = { hour: 'S_hour()', minute: 'S_minute()', dayofweek: 'S_dow()', nyhour: 'S_nyhour()', spread: 'S_spread()', entry: 'entry', risk: 'risk' };

// A stable magic number from the strategy id (so two exported EAs never
// manage each other's trades), 9 digits.
function magicFor(id) { let h = 2166136261; for (const ch of id) { h ^= ch.charCodeAt(0); h = Math.imul(h, 16777619) >>> 0; } return 100000000 + (h % 800000000); }
const q = s => String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/[\r\n]+/g, ' ');

function toMq5(S, opts) {
    opts = opts || {};
    const today = opts.date || new Date().toISOString().slice(0, 10);
    // one handle per distinct MT5 indicator call (upper/lower bands share one)
    const handles = [], hIndex = {};
    const fnName = {};
    for (const x of S.indicators) {
        fnName[x.name] = 'I_' + x.name;
        if (x.mql.handle && hIndex[x.mql.handle] === undefined) { hIndex[x.mql.handle] = handles.length; handles.push(x.mql.handle); }
    }
    const names = Object.assign({}, PRICE_FN, fnName);
    const ex = (rule) => X.toMql(rule.ast, names, SCALAR_MQL);
    const side = (s, field, dflt) => S.sides[s] && S.sides[s][field] ? ex(S.sides[s][field]) : dflt;
    const hasTarget = s => !!(S.sides[s] && S.sides[s].target), hasTrail = s => !!(S.sides[s] && S.sides[s].trail), hasExit = s => !!(S.sides[s] && S.sides[s].exit);
    const o = S.options, L = [];
    const rule = (s, f) => S.sides[s] && S.sides[s][f] ? S.sides[s][f].text : '—';
    L.push(
        '//+------------------------------------------------------------------+',
        '//| ' + S.name,
        '//| Generated by ICT Gold Bot\'s EA converter from src/ea/strategies/' + S.id + '.json on ' + today + '.',
        '//| Change the strategy file and export again rather than editing this.',
        '//|',
        '//| Timeframe: ' + S.timeframe + ' (' + S.mqlTf + '). Rules are checked once per new candle,',
        '//| on finished candles only ([1] = the last finished candle).',
        ...(S.indicators.length ? ['//| Indicators: ' + S.indicators.map(x => x.name + ' = ' + x.text).join(', ')] : []),
        ...['buy', 'sell'].filter(s => S.sides[s]).map(s => '//| ' + s.toUpperCase() + ' when ' + rule(s, 'when') + '; stop ' + rule(s, 'stop') + (hasTarget(s) ? '; target ' + rule(s, 'target') : '; no target') + (hasTrail(s) ? '; trail ' + rule(s, 'trail') : '') + (hasExit(s) ? '; exit when ' + rule(s, 'exit') : '')),
        '//| Max ' + o.maxOpen + ' open; ' + (o.holdOvernight ? 'held overnight' : 'closed before the daily break') + (o.maxBars ? '; closed after ' + o.maxBars + ' candles' : '') + (o.breakevenR ? '; breakeven at ' + o.breakevenR + 'R' : '') + '.',
        '//|',
        '//| Times are the broker\'s server clock. They assume XM-style server time',
        '//| (New York + 7 hours, daily break about 23:55-01:05). Check yours.',
        '//| Test it in the Strategy Tester ("Every tick based on real ticks")',
        '//| and on a demo account before using it with real money.',
        '//+------------------------------------------------------------------+',
        '#property copyright "Generated from ' + q(S.id) + '.json"',
        '#property version   "1.00"',
        '#property description "' + q(S.name).slice(0, 120) + '"',
        '',
        '#include <Trade\\Trade.mqh>',
        '',
        'input double InpRiskPercent     = 0.5;    // Risk per trade, % of balance',
        'input double InpMaxLots         = 0.02;   // Largest lot size',
        'input double InpMaxCostFrac     = 0.10;   // Skip a trade if the spread is more than this share of the stop',
        'input ulong  InpMagic           = ' + magicFor(S.id) + ';  // Magic number: marks this EA\'s trades',
        'input bool   InpCloseBeforeBreak = ' + (o.holdOvernight ? 'false' : 'true') + ';  // Close trades at 23:35 server time',
        'input int    InpSlippagePoints  = 30;     // Allowed slippage on market orders, in points',
        '',
        '#define TF ' + S.mqlTf,
        '#define MAX_OPEN ' + o.maxOpen,
        '#define MAX_BARS ' + o.maxBars,
        '#define BREAKEVEN_R ' + (o.breakevenR ? String(o.breakevenR).replace(/^(\d+)$/, '$1.0') : '0.0'),
        '#define STRATEGY_ID "' + q(S.id) + '"',
        '',
        'CTrade   trade;',
        'bool     g_bad = false;          // set when an indicator or price has no value yet',
        'datetime g_entryBar = 0, g_exitBar = 0;',
    );
    handles.forEach((h, i) => L.push('int      h' + i + ' = INVALID_HANDLE;   // ' + h));
    L.push('',
        '//--- values: every read marks g_bad when the value is missing ---------------',
        'double Buf(int h, int buffer, int shift)',
        '  {',
        '   double v[1];',
        '   if(h == INVALID_HANDLE || CopyBuffer(h, buffer, shift, 1, v) != 1 || v[0] == EMPTY_VALUE) { g_bad = true; return 0.0; }',
        '   return v[0];',
        '  }',
        'double Chk(double v) { if(v == 0.0) g_bad = true; return v; }',
        'double P_open(int s)     { return Chk(iOpen(_Symbol, TF, s)); }',
        'double P_high(int s)     { return Chk(iHigh(_Symbol, TF, s)); }',
        'double P_low(int s)      { return Chk(iLow(_Symbol, TF, s)); }',
        'double P_close(int s)    { return Chk(iClose(_Symbol, TF, s)); }',
        'double P_volume(int s)   { return Chk((double)iVolume(_Symbol, TF, s)); }',
        'double P_median(int s)   { return (P_high(s) + P_low(s)) / 2.0; }',
        'double P_typical(int s)  { return (P_high(s) + P_low(s) + P_close(s)) / 3.0; }',
        'double P_weighted(int s) { return (P_high(s) + P_low(s) + 2.0 * P_close(s)) / 4.0; }',
    );
    for (const x of S.indicators) {
        const m = x.mql;
        if (m.handle) L.push('double I_' + x.name + '(int s) { return Buf(h' + hIndex[m.handle] + ', ' + m.buffer + ', s); }   // ' + x.text);
        else L.push('double I_' + x.name + '(int s) { int i = ' + (m.highest ? 'iHighest' : 'iLowest') + '(_Symbol, TF, ' + m.series + ', ' + m.count + ', s); if(i < 0) { g_bad = true; return 0.0; } return Chk(' + m.get + '(_Symbol, TF, i)); }   // ' + x.text);
    }
    L.push(
        '//--- the broker\'s clock when the current candle opened',
        'int    BarClock(MqlDateTime &d) { return TimeToStruct(iTime(_Symbol, TF, 0), d) ? 1 : 0; }',
        'double S_hour()   { MqlDateTime d; BarClock(d); return (double)d.hour; }',
        'double S_minute() { MqlDateTime d; BarClock(d); return (double)d.min; }',
        'double S_dow()    { MqlDateTime d; BarClock(d); return (double)d.day_of_week; }',
        'double S_nyhour() { return (double)(((int)S_hour() + 17) % 24); }   // server time = New York + 7h',
        'double S_spread() { return SymbolInfoDouble(_Symbol, SYMBOL_ASK) - SymbolInfoDouble(_Symbol, SYMBOL_BID); }',
        '',
        '//--- the strategy\'s rules (from ' + S.id + '.json) ----------------------------',
        'bool   BuyWhen()                           { return ' + side('buy', 'when', 'false') + '; }',
        'bool   SellWhen()                          { return ' + side('sell', 'when', 'false') + '; }',
        'double BuyStop(double entry)               { return ' + side('buy', 'stop', '0.0') + '; }',
        'double SellStop(double entry)              { return ' + side('sell', 'stop', '0.0') + '; }',
        'double BuyTarget(double entry, double risk)  { return ' + side('buy', 'target', '0.0') + '; }',
        'double SellTarget(double entry, double risk) { return ' + side('sell', 'target', '0.0') + '; }',
        'double BuyTrail(double entry, double risk)   { return ' + side('buy', 'trail', '0.0') + '; }',
        'double SellTrail(double entry, double risk)  { return ' + side('sell', 'trail', '0.0') + '; }',
        'bool   BuyExit(double entry, double risk)    { return ' + side('buy', 'exit', 'false') + '; }',
        'bool   SellExit(double entry, double risk)   { return ' + side('sell', 'exit', 'false') + '; }',
        '#define HAS_BUY_TARGET ' + (hasTarget('buy') ? 'true' : 'false'),
        '#define HAS_SELL_TARGET ' + (hasTarget('sell') ? 'true' : 'false'),
        '#define HAS_BUY_TRAIL ' + (hasTrail('buy') ? 'true' : 'false'),
        '#define HAS_SELL_TRAIL ' + (hasTrail('sell') ? 'true' : 'false'),
        '#define HAS_BUY_EXIT ' + (hasExit('buy') ? 'true' : 'false'),
        '#define HAS_SELL_EXIT ' + (hasExit('sell') ? 'true' : 'false'),
        '',
    );
    // start-up: create handles, print the last candle's values for comparison with the bot
    const init = ['int OnInit()', '  {'];
    handles.forEach((h, i) => init.push('   h' + i + ' = ' + h + ';'));
    if (handles.length) init.push('   if(' + handles.map((h, i) => 'h' + i + ' == INVALID_HANDLE').join(' || ') + ') { Print(STRATEGY_ID, ": could not create an indicator"); return INIT_FAILED; }');
    init.push('   trade.SetExpertMagicNumber(InpMagic);', '   trade.SetDeviationInPoints(InpSlippagePoints);',
        '   Print(STRATEGY_ID, " started on ", _Symbol, ", ", EnumToString(TF), ", magic ", (string)InpMagic);',
        '   return INIT_SUCCEEDED;', '  }', '', 'void OnDeinit(const int reason)', '  {');
    handles.forEach((h, i) => init.push('   if(h' + i + ' != INVALID_HANDLE) IndicatorRelease(h' + i + ');'));
    init.push('  }', '',
        '// The last finished candle\'s values, printed once a day so they can be',
        '// compared with the bot\'s (Telegram /status shows the same names).',
        'void LogValues()',
        '  {',
        '   g_bad = false;',
        '   string s = STRATEGY_ID;', '   s = s + " values on the last finished candle:";');
    for (const x of S.indicators) init.push('   s = s + " ' + x.name + '=" + DoubleToString(I_' + x.name + '(1), 2);');
    init.push('   s = s + " close=" + DoubleToString(P_close(1), 2);', '   Print(s);', '  }');
    L.push(...init, '');
    L.push(...MQL_BODY.split('\n'));
    return L.join('\n') + '\n';
}

// The part that's the same for every strategy: entries once per new candle,
// sizing, the spread check, exits, breakeven and trailing.
const MQL_BODY = String.raw`//--- the bot's entry hours (server time): none within 15 minutes of the daily
//--- break, in the first hour after the weekly open or the last before the close
bool EntryTimeOK()
  {
   MqlDateTime d; TimeToStruct(TimeCurrent(), d);
   int mod = d.hour * 60 + d.min;
   if(d.day_of_week == 0 || d.day_of_week == 6) return false;
   if(mod >= 23 * 60 + 35 || mod < 85) return false;
   if(d.day_of_week == 1 && mod < 130) return false;
   if(d.day_of_week == 5 && mod >= 22 * 60 + 50) return false;
   return true;
  }
bool CloseBeforeBreakDue()
  {
   MqlDateTime d; TimeToStruct(TimeCurrent(), d);
   return d.hour * 60 + d.min >= 23 * 60 + 35;
  }

//--- the first risk of each trade (|entry - first stop|), kept in a terminal
//--- global variable so it survives a restart
string RiskKey(long id) { return "EA" + IntegerToString((long)InpMagic) + "_" + IntegerToString(id); }
double FirstRisk(long id, double entry, double sl)
  {
   if(GlobalVariableCheck(RiskKey(id))) return GlobalVariableGet(RiskKey(id));
   return MathAbs(entry - sl);
  }

int CountOpen()
  {
   int n = 0;
   for(int i = PositionsTotal() - 1; i >= 0; i--)
     {
      ulong t = PositionGetTicket(i);
      if(t == 0) continue;
      if(PositionGetString(POSITION_SYMBOL) == _Symbol && PositionGetInteger(POSITION_MAGIC) == (long)InpMagic) n++;
     }
   return n;
  }

//--- lots for a stop this far away: InpRiskPercent of the balance, at most
//--- InpMaxLots; the minimum lot is allowed up to 2x the risk (as in the bot)
double LotsFor(double risk)
  {
   double tickValue = SymbolInfoDouble(_Symbol, SYMBOL_TRADE_TICK_VALUE_LOSS);
   double tickSize  = SymbolInfoDouble(_Symbol, SYMBOL_TRADE_TICK_SIZE);
   double step      = SymbolInfoDouble(_Symbol, SYMBOL_VOLUME_STEP);
   double minV      = SymbolInfoDouble(_Symbol, SYMBOL_VOLUME_MIN);
   double maxV      = SymbolInfoDouble(_Symbol, SYMBOL_VOLUME_MAX);
   if(tickValue <= 0.0 || tickSize <= 0.0 || step <= 0.0 || risk <= 0.0) return 0.0;
   double money  = AccountInfoDouble(ACCOUNT_BALANCE) * InpRiskPercent / 100.0;
   double perLot = risk / tickSize * tickValue;
   double lots   = MathFloor(money / perLot / step + 1e-9) * step;
   lots = MathMin(lots, MathMin(maxV, InpMaxLots));
   if(lots < minV)
     {
      if(minV * perLot > 2.0 * money) return 0.0;
      lots = minV;
     }
   return NormalizeDouble(lots, 2);
  }

double MinDistance()
  {
   double stops = (double)SymbolInfoInteger(_Symbol, SYMBOL_TRADE_STOPS_LEVEL) * _Point;
   double tick  = SymbolInfoDouble(_Symbol, SYMBOL_TRADE_TICK_SIZE);
   return MathMax(stops, 3.0 * tick);
  }

void OpenTrade(bool isBuy)
  {
   double ask = SymbolInfoDouble(_Symbol, SYMBOL_ASK), bid = SymbolInfoDouble(_Symbol, SYMBOL_BID);
   if(ask <= 0.0 || bid <= 0.0) return;
   double entry = isBuy ? ask : bid;
   g_bad = false;
   double stop = isBuy ? BuyStop(entry) : SellStop(entry);
   if(g_bad || (isBuy ? stop >= entry : stop <= entry)) { Print(STRATEGY_ID, ": no trade, the stop formula gave ", DoubleToString(stop, _Digits), " for entry ", DoubleToString(entry, _Digits)); return; }
   double risk = MathAbs(entry - stop), target = 0.0;
   if(isBuy ? HAS_BUY_TARGET : HAS_SELL_TARGET)
     {
      target = isBuy ? BuyTarget(entry, risk) : SellTarget(entry, risk);
      if(g_bad || (isBuy ? target <= entry : target >= entry)) { Print(STRATEGY_ID, ": no trade, the target formula gave ", DoubleToString(target, _Digits)); return; }
     }
   double minD = MinDistance();
   if(risk < minD || (target != 0.0 && MathAbs(target - entry) < minD)) { Print(STRATEGY_ID, ": no trade, stop or target inside the broker's minimum distance"); return; }
   if((ask - bid) / risk > InpMaxCostFrac) { Print(STRATEGY_ID, ": no trade, the spread is ", DoubleToString((ask - bid) / risk * 100.0, 1), "% of the stop"); return; }
   double lots = LotsFor(risk);
   if(lots <= 0.0) { Print(STRATEGY_ID, ": no trade, even the minimum lot would risk too much"); return; }
   stop = NormalizeDouble(stop, _Digits);
   if(target != 0.0) target = NormalizeDouble(target, _Digits);
   bool ok = isBuy ? trade.Buy(lots, _Symbol, 0.0, stop, target, STRATEGY_ID) : trade.Sell(lots, _Symbol, 0.0, stop, target, STRATEGY_ID);
   if(!ok || (trade.ResultRetcode() != TRADE_RETCODE_DONE && trade.ResultRetcode() != TRADE_RETCODE_PLACED))
     { Print(STRATEGY_ID, ": order refused: ", trade.ResultRetcodeDescription()); return; }
   GlobalVariableSet(RiskKey((long)trade.ResultOrder()), risk);
   Print(STRATEGY_ID, isBuy ? ": BUY " : ": SELL ", DoubleToString(lots, 2), " lots, stop ", DoubleToString(stop, _Digits), target != 0.0 ? ", target " + DoubleToString(target, _Digits) : ", no target");
  }

//--- every tick: close before the daily break, breakeven, trailing stop
void ManageTick()
  {
   for(int i = PositionsTotal() - 1; i >= 0; i--)
     {
      ulong t = PositionGetTicket(i);
      if(t == 0 || !PositionSelectByTicket(t)) continue;
      if(PositionGetString(POSITION_SYMBOL) != _Symbol || PositionGetInteger(POSITION_MAGIC) != (long)InpMagic) continue;
      bool   isBuy = PositionGetInteger(POSITION_TYPE) == POSITION_TYPE_BUY;
      double entry = PositionGetDouble(POSITION_PRICE_OPEN), sl = PositionGetDouble(POSITION_SL), tp = PositionGetDouble(POSITION_TP);
      long   id    = PositionGetInteger(POSITION_IDENTIFIER);
      double risk  = FirstRisk(id, entry, sl);
      double bid = SymbolInfoDouble(_Symbol, SYMBOL_BID), ask = SymbolInfoDouble(_Symbol, SYMBOL_ASK);
      double price = isBuy ? bid : ask, gap = MinDistance();
      if(InpCloseBeforeBreak && CloseBeforeBreakDue()) { trade.PositionClose(t); continue; }
      double newSl = sl;
      if(BREAKEVEN_R > 0.0 && risk > 0.0 && (isBuy ? price - entry : entry - price) >= BREAKEVEN_R * risk)
        {
         double be = isBuy ? entry + MathMax(ask - bid, 0.05) : entry - MathMax(ask - bid, 0.05);
         if(isBuy ? be > newSl : (newSl == 0.0 || be < newSl)) newSl = be;
        }
      if(isBuy ? HAS_BUY_TRAIL : HAS_SELL_TRAIL)
        {
         g_bad = false;
         double lv = isBuy ? BuyTrail(entry, risk) : SellTrail(entry, risk);
         if(!g_bad && lv > 0.0 && (isBuy ? lv > newSl : (newSl == 0.0 || lv < newSl))) newSl = lv;
        }
      newSl = NormalizeDouble(newSl, _Digits);
      // only ever tighter, and only where the broker accepts it
      if(newSl != sl && (isBuy ? newSl > sl && newSl < price - gap : (sl == 0.0 || newSl < sl) && newSl > price + gap))
         trade.PositionModify(t, newSl, tp);
     }
  }

//--- once per new candle: exit rule and time limit for trades opened before it.
//--- Returns false when a value isn't ready yet (tried again on the next tick).
bool CheckExits(datetime bar)
  {
   for(int i = PositionsTotal() - 1; i >= 0; i--)
     {
      ulong t = PositionGetTicket(i);
      if(t == 0 || !PositionSelectByTicket(t)) continue;
      if(PositionGetString(POSITION_SYMBOL) != _Symbol || PositionGetInteger(POSITION_MAGIC) != (long)InpMagic) continue;
      datetime opened = (datetime)PositionGetInteger(POSITION_TIME);
      if(opened >= bar) continue;
      bool   isBuy = PositionGetInteger(POSITION_TYPE) == POSITION_TYPE_BUY;
      double entry = PositionGetDouble(POSITION_PRICE_OPEN), sl = PositionGetDouble(POSITION_SL);
      double risk  = FirstRisk(PositionGetInteger(POSITION_IDENTIFIER), entry, sl);
      if(MAX_BARS > 0 && iBarShift(_Symbol, TF, opened, false) >= MAX_BARS) { trade.PositionClose(t); continue; }
      if(isBuy ? HAS_BUY_EXIT : HAS_SELL_EXIT)
        {
         g_bad = false;
         bool ex = isBuy ? BuyExit(entry, risk) : SellExit(entry, risk);
         if(g_bad) return false;
         if(ex) trade.PositionClose(t);
        }
     }
   return true;
  }

//--- once per new candle: the entry rules on the last finished candle
bool CheckEntry()
  {
   if(CountOpen() >= MAX_OPEN) return true;
   g_bad = false;
   bool buy = BuyWhen();
   bool sell = SellWhen();
   if(g_bad) return false;
   if(buy == sell) return true;          // neither, or both: no trade
   if(!EntryTimeOK()) return true;
   OpenTrade(buy);
   return true;
  }

void OnTick()
  {
   datetime bar = iTime(_Symbol, TF, 0);
   if(bar == 0) return;
   ManageTick();
   if(g_exitBar != bar && CheckExits(bar)) g_exitBar = bar;
   if(g_entryBar != bar && CheckEntry())
     {
      g_entryBar = bar;
      MqlDateTime d; TimeToStruct(bar, d);
      static int lastLogDay = -1;
      if(d.day_of_year != lastLogDay) { lastLogDay = d.day_of_year; LogValues(); }
     }
  }
`;

